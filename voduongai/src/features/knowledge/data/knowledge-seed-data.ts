const NOW = "2026-06-01T00:00:00.000Z";

type SeedInput = {
  id: string;
  title: string;
  summary: string;
  content: string;
  type: KnowledgeType;
  category: string;
  goal: string[];
  persona: string[];
  difficulty: Difficulty;
  estimatedTime: string;
  learningOutcome: string;
  tags: string[];
  aiTools: string[];
  practice: string;
  reflectionQuestions: string[];
  nextStep: string;
  companionNote?: string;
  featured?: boolean;
  premium?: boolean;
  relatedAssets?: string[];
};

function seed(input: SeedInput): KnowledgeAsset {
  return {
    id: input.id,
    slug: input.id,
    title: input.title,
    summary: input.summary,
    content: input.content,
    type: input.type,
    status: KnowledgeStatus.PUBLISHED,
    language: "vi",
    thumbnail: `/images/knowledge/${input.id}.jpg`,
    createdAt: NOW,
    updatedAt: NOW,
    dna: {
      goal: input.goal,
      persona: input.persona,
      difficulty: input.difficulty,
      estimatedTime: input.estimatedTime,
      learningOutcome: input.learningOutcome,
      category: input.category,
      tags: input.tags,
      aiTools: input.aiTools,
      industry: ["Văn phòng"],
      role: input.persona,
    },
    relationship: {
      prerequisites: [],
      relatedAssets: input.relatedAssets ?? [],
      relatedPrompts: [],
      relatedTemplates: [],
      relatedSOPs: [],
      relatedFrameworks: [],
      relatedWorkflows: [],
      relatedCaseStudies: [],
    },
    growth: {
      practice: input.practice,
      reflectionQuestions: input.reflectionQuestions,
      nextStep: input.nextStep,
      companionNote: input.companionNote,
    },
    system: {
      publishedAt: NOW,
      author: "VO DUONG AI",
      knowledgeSteward: "VO DUONG AI",
      premium: input.premium ?? false,
      featured: input.featured ?? false,
      verified: true,
      version: 1,
    },
  };
}

